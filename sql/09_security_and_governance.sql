USE ROLE ACCOUNTADMIN;

-- ==============================================================================
-- Part 1: Role-Based Access Control (RBAC) Setup
-- ==============================================================================

-- 1. Create Functional Roles
CREATE ROLE IF NOT EXISTS RETAIL_INGEST_ROLE;
CREATE ROLE IF NOT EXISTS RETAIL_ANALYST_ROLE;
CREATE ROLE IF NOT EXISTS RETAIL_FINANCE_ROLE;
CREATE ROLE IF NOT EXISTS RETAIL_DATA_ENGINEER_ROLE;

-- Hierarchy: Grant roles to SYSADMIN/ACCOUNTADMIN
GRANT ROLE RETAIL_INGEST_ROLE TO ROLE SYSADMIN;
GRANT ROLE RETAIL_ANALYST_ROLE TO ROLE SYSADMIN;
GRANT ROLE RETAIL_FINANCE_ROLE TO ROLE SYSADMIN;
GRANT ROLE RETAIL_DATA_ENGINEER_ROLE TO ROLE SYSADMIN;

-- 2. Grant Warehouse Permissions
GRANT USAGE ON WAREHOUSE RETAIL_INGEST_WH TO ROLE RETAIL_INGEST_ROLE;
GRANT USAGE ON WAREHOUSE RETAIL_ANALYTICS_WH TO ROLE RETAIL_ANALYST_ROLE;
GRANT USAGE ON WAREHOUSE RETAIL_ANALYTICS_WH TO ROLE RETAIL_FINANCE_ROLE;
GRANT USAGE ON WAREHOUSE RETAIL_TRANSFORM_WH TO ROLE RETAIL_DATA_ENGINEER_ROLE;

-- 3. Grant Database and Schema Permissions
GRANT USAGE ON DATABASE RETAIL_ANALYTICS TO ROLE RETAIL_ANALYST_ROLE;
GRANT USAGE ON DATABASE RETAIL_ANALYTICS TO ROLE RETAIL_FINANCE_ROLE;
GRANT USAGE ON DATABASE RETAIL_ANALYTICS TO ROLE RETAIL_DATA_ENGINEER_ROLE;

GRANT USAGE ON SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_ANALYST_ROLE;
GRANT USAGE ON SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_FINANCE_ROLE;
GRANT USAGE ON SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_DATA_ENGINEER_ROLE;

GRANT USAGE ON SCHEMA RETAIL_ANALYTICS.MARTS TO ROLE RETAIL_ANALYST_ROLE;
GRANT USAGE ON SCHEMA RETAIL_ANALYTICS.MARTS TO ROLE RETAIL_FINANCE_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_ANALYST_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_FINANCE_ROLE;
GRANT ALL PRIVILEGES ON SCHEMA RETAIL_ANALYTICS.CORE TO ROLE RETAIL_DATA_ENGINEER_ROLE;

GRANT SELECT ON ALL VIEWS IN SCHEMA RETAIL_ANALYTICS.MARTS TO ROLE RETAIL_ANALYST_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA RETAIL_ANALYTICS.MARTS TO ROLE RETAIL_FINANCE_ROLE;

-- ==============================================================================
-- Part 2: Dynamic Data Masking Policy (Column-Level Security)
-- ==============================================================================

USE DATABASE RETAIL_ANALYTICS;
USE SCHEMA GOVERNANCE;

-- Unset existing masking policies if already applied (allows idempotent re-runs)
ALTER TABLE IF EXISTS RETAIL_ANALYTICS.CORE.DIM_CUSTOMERS
MODIFY COLUMN email UNSET MASKING POLICY;

ALTER TABLE IF EXISTS RETAIL_ANALYTICS.CORE.DIM_CUSTOMERS
MODIFY COLUMN phone UNSET MASKING POLICY;

CREATE OR REPLACE MASKING POLICY PII_MASKING_POLICY
AS (val STRING) RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'RETAIL_DATA_ENGINEER_ROLE')
      THEN val
    ELSE '***MASKED***'
  END;

-- Apply Masking Policy to PII Columns in DIM_CUSTOMERS
ALTER TABLE RETAIL_ANALYTICS.CORE.DIM_CUSTOMERS
MODIFY COLUMN email
SET MASKING POLICY RETAIL_ANALYTICS.GOVERNANCE.PII_MASKING_POLICY;

ALTER TABLE RETAIL_ANALYTICS.CORE.DIM_CUSTOMERS
MODIFY COLUMN phone
SET MASKING POLICY RETAIL_ANALYTICS.GOVERNANCE.PII_MASKING_POLICY;

-- ==============================================================================
-- Part 3: Row Access Policy (Row-Level Security)
-- ==============================================================================

CREATE OR REPLACE TABLE RETAIL_ANALYTICS.GOVERNANCE.USER_REGION_ACCESS (
    role_name STRING,
    allowed_state STRING
);

TRUNCATE TABLE RETAIL_ANALYTICS.GOVERNANCE.USER_REGION_ACCESS;

INSERT INTO RETAIL_ANALYTICS.GOVERNANCE.USER_REGION_ACCESS VALUES
    ('RETAIL_ANALYST_ROLE', 'NY'),
    ('RETAIL_FINANCE_ROLE', 'NY'),
    ('RETAIL_FINANCE_ROLE', 'CA'),
    ('RETAIL_FINANCE_ROLE', 'TX');

-- Detach existing row access policy if already applied (allows idempotent re-runs)
ALTER TABLE IF EXISTS RETAIL_ANALYTICS.CORE.FACT_ORDERS
DROP ALL ROW ACCESS POLICIES;

CREATE OR REPLACE ROW ACCESS POLICY STATE_ACCESS_POLICY
AS (state_value STRING) RETURNS BOOLEAN ->
    CURRENT_ROLE() = 'ACCOUNTADMIN'
    OR CURRENT_ROLE() = 'RETAIL_DATA_ENGINEER_ROLE'
    OR EXISTS (
        SELECT 1
        FROM RETAIL_ANALYTICS.GOVERNANCE.USER_REGION_ACCESS a
        WHERE a.role_name = CURRENT_ROLE()
          AND a.allowed_state = state_value
    );

-- Apply Row Access Policy on FACT_ORDERS shipping_state
ALTER TABLE RETAIL_ANALYTICS.CORE.FACT_ORDERS
ADD ROW ACCESS POLICY RETAIL_ANALYTICS.GOVERNANCE.STATE_ACCESS_POLICY
ON (shipping_state);

